"""High-contribution leader pump-fade short factor.

This research factor targets a structure that appears in high-yield meme
leader samples but is mostly outside the current downtrend-continuation
factors: learned high-contribution short symbols that are still near a pump
high, with active volume and a first weak/stalling bar.  It uses only
as-of OHLCV/OI/funding fields plus an offline symbol edge file generated by
leader learning.
"""

from __future__ import annotations

import os

import numpy as np
import pandas as pd


def _env_float(name: str, default: float) -> float:
    try:
        return float(os.getenv(name, str(default)))
    except Exception:
        return default


def _safe_series(df: pd.DataFrame, name: str, default: float = 0.0) -> pd.Series:
    if name in df.columns:
        return pd.to_numeric(df[name], errors="coerce").ffill().fillna(default)
    return pd.Series(default, index=df.index, dtype=float)


def _clip01(value: pd.Series) -> pd.Series:
    return value.clip(lower=0.0, upper=1.0)


def _frame_symbol(df: pd.DataFrame) -> str:
    raw = df.attrs.get("symbol") or df.attrs.get("market_symbol") or ""
    return str(raw or "").strip().upper().replace("/", "")


def _leader_short_score(symbol: str) -> float:
    edge_file = os.getenv(
        "MEME_LEADER_HIGH_CONTRIB_SHORT_EDGE_FILE",
        "factors/crypto/trading_feedback/leader_learning/meme_yield_breakthrough_20260617_high_contrib.symbols.csv",
    ).strip()
    if not symbol or not edge_file:
        return 0.0
    try:
        from cz.trading.crypto.meme.leader_edge import leader_symbol_edge_from_file
    except Exception:
        return 0.0
    edge = leader_symbol_edge_from_file(
        symbol,
        edge_file,
        min_score=_env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_SCORE", 62.0),
        min_samples=int(_env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_SAMPLES", 1.0)),
        min_win_rate=_env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_WIN_RATE", 80.0),
    )
    if edge is None or getattr(edge, "direction", "") != "SHORT":
        return 0.0
    try:
        return float(getattr(edge, "score", 0.0))
    except Exception:
        return 0.0


def calculate_factor(df: pd.DataFrame) -> pd.Series:
    if df is None or len(df) < 70:
        return pd.Series(0.0, index=getattr(df, "index", None))

    symbol_score = _leader_short_score(_frame_symbol(df))
    min_score = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_SCORE", 62.0)
    if symbol_score < min_score:
        return pd.Series(0.0, index=df.index)

    open_ = _safe_series(df, "open")
    high = _safe_series(df, "high")
    low = _safe_series(df, "low")
    close = _safe_series(df, "close")
    volume = _safe_series(df, "volume", 1.0)
    quote_volume = _safe_series(df, "quote_volume")
    taker_buy_quote = _safe_series(df, "taker_buy_quote")
    oi = _safe_series(df, "open_interest")
    funding = _safe_series(df, "funding_rate")

    min_output = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_OUTPUT", 0.24)
    max_output = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MAX_OUTPUT", 0.88)
    min_ret60 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_RET60_PCT", 1.0)
    min_ret240 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_RET240_PCT", -999.0)
    min_from_low60 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_FROM_LOW60_PCT", 2.0)
    min_from_low240 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_FROM_LOW240_PCT", 4.0)
    max_from_high60 = abs(_env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MAX_FROM_HIGH60_PCT", 4.5))
    min_ret15 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_RET15_PCT", -1.0)
    max_ret5 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MAX_RET5_PCT", 4.0)
    max_ret1 = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MAX_RET1_PCT", 1.8)
    min_vol_ratio = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MIN_VOL_RATIO", 0.35)
    max_vol_ratio = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MAX_VOL_RATIO", 4.0)
    max_taker_buy_ratio = _env_float("MEME_LEADER_HIGH_CONTRIB_SHORT_MAX_TAKER_BUY_RATIO", 0.70)

    ret1 = close.pct_change(1) * 100.0
    ret5 = close.pct_change(5) * 100.0
    ret15 = close.pct_change(15) * 100.0
    ret60 = close.pct_change(60) * 100.0
    ret240 = close.pct_change(120) * 100.0

    high60 = high.rolling(60, min_periods=20).max()
    low60 = low.rolling(60, min_periods=20).min()
    low240 = low.rolling(120, min_periods=40).min().fillna(low60)
    from_high60 = (close / high60.replace(0.0, np.nan) - 1.0) * 100.0
    from_low60 = (close / low60.replace(0.0, np.nan) - 1.0) * 100.0
    from_low240 = (close / low240.replace(0.0, np.nan) - 1.0) * 100.0

    vol_base = volume.rolling(30, min_periods=12).median().shift(1).replace(0.0, np.nan)
    vol_ratio = (volume / vol_base).replace([np.inf, -np.inf], np.nan).fillna(1.0)
    taker_buy_ratio = (
        taker_buy_quote / quote_volume.replace(0.0, np.nan)
    ).replace([np.inf, -np.inf], np.nan).fillna(0.50)
    oi_roc20 = oi.pct_change(20).replace([np.inf, -np.inf], np.nan).fillna(0.0) * 100.0

    bar_range = (high - low).replace(0.0, np.nan)
    close_pos = (close - low) / bar_range
    upper_wick = (high - pd.concat([open_, close], axis=1).max(axis=1)) / bar_range
    weak_close = (close <= open_) | (ret1 <= max_ret1)

    symbol_strength = min(1.0, max(0.0, symbol_score / 90.0))
    extension = pd.concat(
        [
            _clip01((ret60.fillna(0.0) - min_ret60) / 18.0),
            _clip01((ret240.fillna(0.0) - min_ret240) / 28.0),
            _clip01((from_low240.fillna(0.0) - min_from_low240) / 20.0),
        ],
        axis=1,
    ).max(axis=1)
    near_high = 1.0 - _clip01((-from_high60.fillna(-999.0)) / max(max_from_high60, 0.5))
    stall = (
        0.35 * _clip01((max_ret5 - ret5.fillna(0.0)) / 8.0)
        + 0.25 * _clip01((max_ret1 - ret1.fillna(0.0)) / 4.0)
        + 0.20 * _clip01((0.76 - close_pos.fillna(0.5)) / 0.60)
        + 0.20 * _clip01(upper_wick.fillna(0.0) / 0.35)
    )
    activity = _clip01((vol_ratio - min_vol_ratio) / 1.6) * (1.0 - _clip01((vol_ratio - max_vol_ratio) / 8.0))
    sell_pressure = _clip01((max_taker_buy_ratio - taker_buy_ratio) / max(max_taker_buy_ratio - 0.40, 0.08))
    crowding = 0.65 * _clip01(oi_roc20.abs() / 12.0) + 0.35 * _clip01(funding.fillna(0.0).clip(lower=0.0) / 0.25)

    score = symbol_strength * (
        0.30 * extension
        + 0.22 * near_high
        + 0.20 * stall
        + 0.12 * activity
        + 0.10 * sell_pressure
        + 0.06 * crowding
    )
    valid = (
        (ret60 >= min_ret60)
        & ((min_ret240 <= -900.0) | (ret240 >= min_ret240))
        & (ret15 >= min_ret15)
        & (ret5 <= max_ret5)
        & (ret1 <= max_ret1)
        & (from_high60 >= -max_from_high60)
        & (from_low60 >= min_from_low60)
        & (from_low240 >= min_from_low240)
        & (vol_ratio >= min_vol_ratio)
        & (vol_ratio <= max_vol_ratio)
        & (taker_buy_ratio <= max_taker_buy_ratio)
        & (weak_close | (upper_wick.fillna(0.0) >= 0.10) | (close_pos.fillna(0.5) <= 0.68))
    )

    out = pd.Series(0.0, index=df.index)
    out = out.mask(valid, -score.clip(lower=0.0, upper=max_output))
    return out.where(out.abs() >= min_output, 0.0).fillna(0.0)
